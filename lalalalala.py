# Подключаем модуль random
# Он нужен для случайных чисел и событий
import random

# Подключаем модуль time
# Нужен для задержек в игре
import time


# ==========================================
# ДАННЫЕ ИГРОКА
# ==========================================

# Просим игрока ввести имя
player_name = input("Введите имя путешественника: ")

# Начальное количество денег
money = 500

# Начальное здоровье
health = 100

# Начальное количество очков
score = 0

# Счётчик дней
days = 1

# Пустой список инвентаря
inventory = []


# ==========================================
# СПИСОК ГОРОДОВ
# ==========================================

# Словарь городов и маршрутов
# Ключ = текущий город
# Значение = список доступных городов
cities = {

    "Лондон": ["Париж", "Берлин"],

    "Париж": ["Рим", "Мадрид"],

    "Берлин": ["Москва", "Прага"],

    "Рим": ["Каир", "Афины"],

    "Москва": ["Пекин", "Токио"],

    "Пекин": ["Сеул", "Бангкок"],

    "Токио": ["Сидней"],
}

# Стартовый город игрока
current_city = "Лондон"


# ==========================================
# СЛУЧАЙНЫЕ СОБЫТИЯ
# ==========================================

# Список событий игры
events = [

    {
        # Текст события
        "text": "Вы нашли клад!",

        # Игрок получает деньги
        "money": 100,

        # Здоровье не меняется
        "health": 0
    },

    {
        "text": "На вас напали грабители!",

        # Игрок теряет деньги
        "money": -50,

        # Игрок теряет здоровье
        "health": -20
    },

    {
        "text": "Вы вкусно поели в ресторане.",

        "money": -30,

        # Восстанавливаем здоровье
        "health": 10
    },

    {
        "text": "Вы заболели в дороге.",

        "money": -20,

        "health": -30
    },

    {
        "text": "Вы выиграли билет!",

        "money": 80,

        "health": 0
    }
]


# ==========================================
# ВОПРОСЫ ВИКТОРИНЫ
# ==========================================

# Список вопросов
questions = [

    {
        # Вопрос
        "question": "Столица Франции?",

        # Правильный ответ
        "answer": "Париж"
    },

    {
        "question": "Столица Японии?",

        "answer": "Токио"
    },

    {
        "question": "Столица Италии?",

        "answer": "Рим"
    },

    {
        "question": "Столица России?",

        "answer": "Москва"
    }
]


# ==========================================
# ФУНКЦИЯ ПОКАЗА СТАТИСТИКИ
# ==========================================

# Создаём функцию вывода статистики
def show_stats():

    # Печатаем информацию об игроке
    print("\n========================")

    print("Игрок:", player_name)

    print("Город:", current_city)

    print("День:", days)

    print("Деньги:", money)

    print("Здоровье:", health)

    print("Очки:", score)

    print("Инвентарь:", inventory)

    print("========================\n")


# ==========================================
# ФУНКЦИЯ СЛУЧАЙНОГО СОБЫТИЯ
# ==========================================

def random_event():

    # Используем глобальные переменные
    global money
    global health

    # Случайно выбираем событие
    event = random.choice(events)

    print("\nСЛУЧАЙНОЕ СОБЫТИЕ")

    # Выводим текст события
    print(event["text"])

    # Меняем деньги игрока
    money += event["money"]

    # Меняем здоровье игрока
    health += event["health"]

    # Показываем изменения
    print("Изменение денег:", event["money"])

    print("Изменение здоровья:", event["health"])


# ==========================================
# ФУНКЦИЯ МАГАЗИНА
# ==========================================

def shop():

    # Используем глобальную переменную денег
    global money

    # Список товаров магазина
    items = {

        "Аптечка": 50,

        "Компас": 30,

        "Еда": 20,

        "Фонарик": 40
    }

    print("\nМАГАЗИН")

    # Выводим товары
    for item, price in items.items():

        print(item, "-", price)

    # Спрашиваем выбор игрока
    choice = input("Что купить? ")

    # Проверяем наличие товара
    if choice in items:

        # Проверяем хватает ли денег
        if money >= items[choice]:

            # Снимаем деньги
            money -= items[choice]

            # Добавляем предмет в инвентарь
            inventory.append(choice)

            print("Вы купили:", choice)

        else:

            print("Недостаточно денег")

    else:

        print("Такого предмета нет")


# ==========================================
# ФУНКЦИЯ ВИКТОРИНЫ
# ==========================================

def quiz():

    # Используем глобальную переменную очков
    global score

    # Случайно выбираем вопрос
    question = random.choice(questions)

    print("\nВИКТОРИНА")

    # Показываем вопрос
    print(question["question"])

    # Получаем ответ игрока
    answer = input("Ваш ответ: ")

    # Проверяем правильность ответа
    if answer.lower() == question["answer"].lower():

        print("Правильно!")

        # Начисляем очки
        score += 10

    else:

        print("Неправильно!")

        # Показываем правильный ответ
        print("Правильный ответ:", question["answer"])


# ==========================================
# ФУНКЦИЯ ПУТЕШЕСТВИЯ
# ==========================================

def travel():

    # Используем глобальные переменные
    global current_city
    global money
    global days

    # Проверяем есть ли маршруты
    if current_city not in cities:

        print("Из этого города нельзя путешествовать")

        return

    print("\nДоступные города:")

    # Получаем список городов
    available = cities[current_city]

    # Выводим список городов
    for city in available:

        print("-", city)

    # Спрашиваем куда поехать
    destination = input("Куда поехать? ")

    # Проверяем доступность города
    if destination in available:

        # Случайная стоимость поездки
        cost = random.randint(40, 120)

        print("Стоимость поездки:", cost)

        # Проверяем хватает ли денег
        if money >= cost:

            # Вычитаем деньги
            money -= cost

            # Меняем текущий город
            current_city = destination

            # Увеличиваем день
            days += 1

            print("Вы прибыли в:", current_city)

            # Запускаем случайное событие
            random_event()

        else:

            print("Недостаточно денег")

    else:

        print("Нельзя поехать в этот город")


# ==========================================
# ФУНКЦИЯ ОТДЫХА
# ==========================================

def rest():

    # Используем глобальные переменные
    global health
    global days

    print("\nВы отдыхаете...")

    # Задержка 1 секунда
    time.sleep(1)

    # Восстанавливаем здоровье
    health += 20

    # Проверяем максимум здоровья
    if health > 100:

        health = 100

    # Увеличиваем день
    days += 1

    print("Здоровье восстановлено")


# ==========================================
# ГЛАВНЫЙ ИГРОВОЙ ЦИКЛ
# ==========================================

# Бесконечный цикл игры
while True:

    # Проверяем здоровье
    if health <= 0:

        print("\nИгра окончена.")

        print("Ваш персонаж потерял здоровье.")

        break

    # Проверяем деньги
    if money <= 0:

        print("\nИгра окончена.")

        print("У вас закончились деньги.")

        break

    # Показываем статистику
    show_stats()

    # Меню игры
    print("1 - Путешествовать")

    print("2 - Магазин")

    print("3 - Викторина")

    print("4 - Отдых")

    print("5 - Выход")

    # Получаем выбор игрока
    choice = input("Выберите действие: ")

    # ======================================
    # ВЫБОР ДЕЙСТВИЯ
    # ======================================

    # Путешествие
    if choice == "1":

        travel()

    # Магазин
    elif choice == "2":

        shop()

    # Викторина
    elif choice == "3":

        quiz()

    # Отдых
    elif choice == "4":

        rest()

    # Выход
    elif choice == "5":

        print("\nСпасибо за игру!")

        break

    # Неверный ввод
    else:

        print("Неверный выбор")


# ==========================================
# КОНЕЦ ИГРЫ
# ==========================================

print("\n======== ИТОГИ ========")

print("Игрок:", player_name)

print("Очки:", score)

print("Прожито дней:", days)

print("Финальный город:", current_city)

print("=======================")
